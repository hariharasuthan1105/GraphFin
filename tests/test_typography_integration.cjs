const fs = require('fs');
const path = require('path');
const assert = require('assert/strict');
const ts = require('../frontend/node_modules/typescript');
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022,esModuleInterop:true}}).outputText,filename);
require('./test_analysis_recovery.ts');
const {parseDelimitedText,parseJsonTransactions,autoDetectColumnMapping,buildTransactionRecordsDetailed} = require('../frontend/src/research/datasetAnalysis/parser.ts');
const {analyzeTransactionGraph} = require('../frontend/src/research/datasetAnalysis/engine.ts');
const {safeSummary} = require('../frontend/src/research/sessionMetadata.ts');
const input='source,destination,amount,currency\nA,B,100,INR\nB,C,200,INR\n,C,300,INR';
const table=parseDelimitedText(input);
const parsed=buildTransactionRecordsDetailed(table,autoDetectColumnMapping(table.headers));
assert.equal(parsed.acceptedRows,2);assert.equal(parsed.rejectedRows,1);assert.equal(parsed.rawTotalRows,3);
const result=analyzeTransactionGraph(parsed.records,'synthetic.csv',input.length,undefined,parsed.rawTotalRows,parsed.rejectedRows);
assert.equal(result.summary.totalVolume,300);assert.equal(result.summary.currency,'INR');assert.equal(result.summary.totalRowsRejected,1);
assert.throws(()=>parseDelimitedText('source,destination,amount\nA,B,1\nB,C,2',1),/record limit/);
assert.throws(()=>parseJsonTransactions(JSON.stringify(Array.from({length:25001},()=>({source:'A',destination:'B',amount:1})))),/record limit/);
assert.throws(()=>parseDelimitedText('source,destination,amount\n"A,B,10'),/Unclosed/);
assert.throws(()=>parseJsonTransactions('[null]'));
const unknown=analyzeTransactionGraph([{transaction_id:'1',source:'A',destination:'B',amount:10}]);
assert.equal(unknown.summary.currency,'Unknown');
assert.ok(!('rawCsvContent' in safeSummary({...result.summary,rawCsvContent:'private input'})));
console.log('PASS: rejected counts, INR volume, CSV/JSON bounds, malformed input, unknown currency, safe metadata.');
